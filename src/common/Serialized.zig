const std = @import("std");

const cstring = @cImport(@cInclude("string.h"));
const hs = @cImport(@cInclude("hs/hs.h"));

const check = @import("../common.zig").check;
const Database = @import("Database.zig").Database;
const Pattern = @import("../compile.zig").Pattern;

const runtime = @import("../runtime.zig");

const MatchEvent = runtime.MatchEvent;
const ScanOptions = runtime.ScanOptions;

buf: []u8,
owned: bool = false,

const Serialized = @This();

pub fn init(buf: []u8) Serialized {
    return .{
        .buf = buf,
    };
}

pub fn deinit(self: *const Serialized) void {
    if (self.owned) {
        std.c.free(self.buf.ptr);
    }
}

/// Serialize a pattern database to a stream of bytes.
pub fn serialize(db: *const Database) !Serialized {
    var buf: ?*const u8 = null;
    var sz: usize = 0;

    try check(hs.hs_serialize_database(@ptrCast(db.ptr), @ptrCast(&buf), &sz));

    return if (buf) |ptr| .{
        .buf = @constCast(@as([*]const u8, @ptrCast(ptr))[0..sz]),
        .owned = true,
    } else error.UnknownError;
}

/// Reconstruct a pattern database from a stream of bytes previously generated by `serialize`.
pub fn deserialize(self: *const Serialized) !Database {
    var db: ?*hs.hs_database_t = null;

    try check(hs.hs_deserialize_database(self.buf.ptr, self.buf.len, &db));

    return if (db) |ptr| .{
        .ptr = @ptrCast(ptr),
    } else error.UnknownError;
}

/// Utility function for reporting the size that would be required by a database if it were deserialized.
pub fn databaseSize(self: *const Serialized) !usize {
    var sz: usize = 0;

    try check(hs.hs_serialized_database_size(self.buf.ptr, self.buf.len, &sz));

    return sz;
}

/// Utility function providing information about a serialized database.
pub fn databaseInfo(self: *const Serialized, allocator: std.mem.Allocator) ![]const u8 {
    var db_info: ?[*]u8 = null;

    try check(hs.hs_serialized_database_info(self.buf.ptr, self.buf.len, &db_info));
    defer std.c.free(db_info);

    return if (db_info) |p|
        allocator.dupe(u8, p[0..cstring.strlen(p)])
    else
        error.UnknownError;
}

